// Embed templates/brain/** into src/core/templates.gen.ts so both the npm package and the
// Bun-compiled binary carry them (a compiled binary has no templates folder on disk).
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

function embed(root) {
  const files = {};
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const full = path.join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else files[path.relative(root, full).split(path.sep).join('/')] = readFileSync(full, 'utf8');
    }
  };
  walk(root);
  return files;
}
const files = embed('templates/brain');
const hub = embed('templates/hub');
writeFileSync(
  'src/core/templates.gen.ts',
  `// Generated by scripts/gen-templates.mjs from templates/. Do not edit.\nexport const TEMPLATES: Record<string, string> = ${JSON.stringify(files, null, 2)};\nexport const HUB_TEMPLATES: Record<string, string> = ${JSON.stringify(hub, null, 2)};\n`,
);
console.log(`embedded ${Object.keys(files).length + Object.keys(hub).length} template files`);
